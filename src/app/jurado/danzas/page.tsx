export default async function JuradoPage() {
  const session = await getSession();
  if (!session || session.role !== "JURADO") {
    redirect("/login");
  }

  let dances: DanceItem[] = [];
  let usingDemo = false;

  try {
    const edition = await getActiveEdition();
    if (edition) {
      // 1. Obtener grupos de danza (Módulo A)
      const dbDanceGroups = await prisma.danceGroup.findMany({
        where: { editionId: edition.id },
        include: {
          fraternity: true,
          danceScores: {
            where: {
              juryId: session.userId,
              status: "SUBMITTED",
            },
          },
        },
        orderBy: [{ entryOrder: "asc" }],
      });

      const danceGroupItems: DanceItem[] = dbDanceGroups.map((g) => ({
        id: g.id,
        order: g.entryOrder || 99,
        status: g.status === "IN_SCORING" ? "ACTIVE" : (g.status as "PENDING" | "CLOSED"),
        categoryName: "Entrada Folklórica",
        categorySlug: "entrada-folklorica",
        danceName: g.danceName,
        fraternityName: g.fraternity.name,
        university: g.fraternity.university,
        city: g.fraternity.city,
        department: g.fraternity.department,
        candidateName: `Fraternidad Oficial (${g.numberOfDancers} bailarines)`,
        candidateTitle: "Módulo A • Grupo de Danza",
        photoUrl: g.photoUrl,
        score: g.danceScores[0]
          ? {
              rawTotal: g.danceScores[0].rawTotal,
              payloadHash: g.danceScores[0].payloadHash || "",
              submittedAt: g.danceScores[0].submittedAt.toISOString(),
            }
          : null,
      }));

      // 2. Obtener candidatas (Módulo B)
      const entries = await prisma.entry.findMany({
        where: { category: { editionId: edition.id } },
        include: {
          category: true,
          runway: true,
          participant: {
            include: { fraternity: true },
          },
          scores: {
            where: {
              juryId: session.userId,
              status: "SUBMITTED",
            },
          },
        },
        orderBy: [
          { category: { order: "asc" } },
          { order: "asc" },
        ],
      });


      const uniqueCandidates = [...new Map(entries.map(e => [e.participantId, e])).values()];
      const now = new Date();
      const candidateItems: DanceItem[] = uniqueCandidates.map((e) => {
        const turns = entries.filter(turn => turn.participantId === e.participantId);
        const rounds = (["GALA", "CASUAL", "TIPICA"] as const).map(type => {
          const turn = turns.find(t => t.runway?.type === type);
          const voted = Boolean(turn?.scores.length);
          const closed = turn?.status === "CLOSED" || turn?.category.status === "CLOSED" || Boolean(turn?.votingClosesAt && now >= turn.votingClosesAt);
          const open = turn && !closed && turn.status === "IN_SCORING" && ["OPEN", "VOTING"].includes(turn.category.status) && Boolean(turn.category.activeRubricId) && (!turn.votingOpensAt || now >= turn.votingOpensAt);
          return { type, name: type === "GALA" ? "Gala" : type === "CASUAL" ? "Casual" : "Típica", status: voted ? "voted" as const : closed ? "closed" as const : open ? "open" as const : "pending" as const, href: !voted && open ? "/jurado/calificar/" + turn.id : undefined, actaHref: turn && voted ? "/jurado/calificar/" + turn.id : undefined };
        });
        const userScore = e.scores[0];
        const assignedPhoto = e.participant.photoUrl;

        return {
          id: e.participantId,
          candidate: { order: Math.min(...turns.map(t => t.order)), categoryName: e.category.name, university: e.participant.fraternity.university, location: [e.participant.fraternity.department, e.participant.fraternity.city].filter(Boolean).join(" • "), id: e.participantId, name: e.participant.fullName, photoUrl: assignedPhoto, fraternity: e.participant.fraternity.name, rounds },
          order: e.order,
          status: rounds.some(r => r.status === "open") ? "ACTIVE" : rounds.every(r => r.status === "closed" || r.status === "voted") ? "CLOSED" : "PENDING",
          categoryName: e.category.name,
          categorySlug: e.category.slug,
          danceName:
            e.participant.bio ||
            e.participant.fraternity.name,
          fraternityName: e.participant.fraternity.name,
          university: e.participant.fraternity.university,
          city: e.participant.fraternity.city,
          department: e.participant.fraternity.department,
          candidateName: e.participant.fullName,
          candidateTitle: `Candidata a ${e.category.name} ${edition.year}`,
          photoUrl: assignedPhoto,
          score: userScore
            ? {
                rawTotal: userScore.rawTotal || 0,
                payloadHash: userScore.payloadHash || "",
                submittedAt: userScore.submittedAt?.toISOString() || "",
              }
            : null,
        };
      });
      dances = [...danceGroupItems, ...candidateItems];
    }
  } catch (error) {
    console.warn("Could not query DB directly, using seed catalog:", error);
    dances = FALLBACK_DANCES;
    usingDemo = true;
  }

  return (
    <div className="min-w-0 max-w-7xl mx-auto py-2 sm:py-4">
      <div className="mb-4">
        <Link
          href="/jurado"
          className="inline-flex items-center gap-2 px-3.5 py-2 rounded-xl text-xs sm:text-sm text-tertiary bg-tertiary/10 hover:bg-tertiary/20 border border-tertiary/30 font-display font-bold transition-all shadow-sm"
        >
          <span className="ms text-lg">arrow_back</span>
          Volver al Menú Principal
        </Link>
      </div>
      {usingDemo && <p role="status" className="mb-4 rounded-xl border border-amber-500/30 bg-amber-950/30 p-4 text-amber-200 text-sm">No se pudo consultar la base de datos. Se muestra el catálogo de demostración.</p>}
      <JuryDancesClient
        juryName={session.name}
        juryCode={session.code || "JUR-04"}
        dances={dances}
      />
    </div>
  );
}
